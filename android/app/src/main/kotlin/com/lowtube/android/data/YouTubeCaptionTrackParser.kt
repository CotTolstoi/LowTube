package com.lowtube.android.data

import com.lowtube.android.model.YouTubeCaptionTrack
import org.json.JSONObject
import java.net.URI

/** Parses only the public caption tracks in a player response, never its translation-language menu. */
internal object YouTubeCaptionTrackParser {
    private const val MAX_TRACKS = 64
    private const val MAX_URL_LENGTH = 4096
    private const val MAX_LANGUAGE_LENGTH = 32
    private const val MAX_LABEL_LENGTH = 128
    private val LANGUAGE_CODE = Regex("[A-Za-z0-9-]{1,32}")

    fun parse(player: JSONObject, expectedVideoId: String): List<YouTubeCaptionTrack> {
        if (expectedVideoId.isBlank()) return emptyList()
        val trackArray = player.optJSONObject("captions")
            ?.optJSONObject("playerCaptionsTracklistRenderer")
            ?.optJSONArray("captionTracks") ?: return emptyList()
        val result = LinkedHashMap<String, YouTubeCaptionTrack>()
        for (index in 0 until minOf(trackArray.length(), MAX_TRACKS)) {
            val item = trackArray.optJSONObject(index) ?: continue
            val language = item.optString("languageCode").takeIf {
                it.length <= MAX_LANGUAGE_LENGTH && LANGUAGE_CODE.matches(it)
            } ?: continue
            val rawUrl = item.optString("baseUrl").takeIf { it.isNotBlank() && it.length <= MAX_URL_LENGTH } ?: continue
            val url = trustedTimedTextUrl(rawUrl, expectedVideoId) ?: continue
            val label = captionLabel(item.optJSONObject("name"))
                .take(MAX_LABEL_LENGTH)
                .ifBlank { language }
            val kind = item.optString("kind")
            val vssId = item.optString("vssId")
            val vttUrl = appendVttFormat(url)
            if (vttUrl.length > MAX_URL_LENGTH) continue
            val track = YouTubeCaptionTrack(
                uri = vttUrl,
                languageCode = language,
                label = label,
                autoGenerated = kind == "asr" || vssId.startsWith("a."),
            )
            val key = "$language|${track.autoGenerated}|$label"
            result.putIfAbsent(key, track)
        }
        return result.values.toList()
    }

    private fun captionLabel(name: JSONObject?): String {
        name ?: return ""
        name.optString("simpleText").takeIf(String::isNotBlank)?.let { return it }
        val runs = name.optJSONArray("runs") ?: return ""
        return buildString {
            for (index in 0 until minOf(runs.length(), 16)) {
                append(runs.optJSONObject(index)?.optString("text").orEmpty())
            }
        }
    }

    private fun trustedTimedTextUrl(raw: String, videoId: String): String? {
        val base = URI("https://www.youtube.com/")
        val candidate = runCatching { base.resolve(URI(raw)) }.getOrNull() ?: return null
        if (candidate.scheme != "https" || candidate.rawUserInfo != null ||
            candidate.port != -1 && candidate.port != 443 || candidate.rawFragment != null ||
            candidate.host?.lowercase() !in setOf("youtube.com", "www.youtube.com") ||
            candidate.path != "/api/timedtext" || candidate.rawQuery.isNullOrBlank() ||
            candidate.toASCIIString().length > MAX_URL_LENGTH
        ) return null
        val videoParameter = candidate.rawQuery.split('&').firstNotNullOfOrNull { pair ->
            val separator = pair.indexOf('=')
            if (separator < 0 || pair.substring(0, separator) != "v") null
            else runCatching { java.net.URLDecoder.decode(pair.substring(separator + 1), "UTF-8") }.getOrNull()
        }
        return candidate.toASCIIString().takeIf { videoParameter == videoId }
    }

    private fun appendVttFormat(url: String): String {
        val queryStart = url.indexOf('?')
        if (queryStart < 0) return "$url?fmt=vtt"
        val prefix = url.substring(0, queryStart)
        val retainedParameters = url.substring(queryStart + 1)
            .split('&')
            .filter { it.substringBefore('=') != "fmt" && it.isNotBlank() }
        return "$prefix?${(retainedParameters + "fmt=vtt").joinToString("&")}"
    }
}
