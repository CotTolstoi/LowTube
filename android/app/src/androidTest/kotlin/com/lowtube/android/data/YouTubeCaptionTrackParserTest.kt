package com.lowtube.android.data

import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.runner.RunWith
import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

@RunWith(AndroidJUnit4::class)
class YouTubeCaptionTrackParserTest {
    @Test
    fun parsesCaptionTracksAndAddsVttFormat() {
        val player = playerWithTracks(
            track(
                "/api/timedtext?v=video123&lang=en&fmt=srv3",
                language = "en",
                name = "English",
            ),
            track(
                "https://www.youtube.com/api/timedtext?v=video123&lang=en&kind=asr",
                language = "en",
                name = "English (auto-generated)",
                kind = "asr",
                vssId = "a.en",
            ),
        )

        val parsed = YouTubeCaptionTrackParser.parse(player, "video123")

        assertEquals(2, parsed.size)
        assertEquals("English", parsed[0].label)
        assertEquals("en", parsed[0].languageCode)
        assertFalse(parsed[0].autoGenerated)
        assertEquals("English (auto-generated)", parsed[1].label)
        assertTrue(parsed[1].autoGenerated)
        assertTrue(parsed[0].uri.startsWith("https://www.youtube.com/api/timedtext?v=video123&lang=en&fmt=vtt"))
        assertEquals(1, Regex("(?:^|&)fmt=").findAll(parsed[0].uri.substringAfter('?')).count())
    }

    @Test
    fun rejectsUntrustedUrlsAndOtherVideoIds() {
        val player = playerWithTracks(
            track("https://attacker.example/api/timedtext?v=video123", name = "Foreign"),
            track("http://www.youtube.com/api/timedtext?v=video123", name = "Insecure"),
            track("https://www.youtube.com/api/timedtext?v=other", name = "Wrong video"),
            track("https://user@www.youtube.com/api/timedtext?v=video123", name = "User info"),
            track("https://www.youtube.com:444/api/timedtext?v=video123", name = "Port"),
            track("https://www.youtube.com/not-timedtext?v=video123", name = "Wrong path"),
        )

        assertTrue(YouTubeCaptionTrackParser.parse(player, "video123").isEmpty())
    }

    @Test
    fun deduplicatesBoundsTracksAndDoesNotPromoteTranslationLanguages() {
        val duplicate = track("/api/timedtext?v=video123&lang=en", language = "en", name = "English")
        val entries = JSONArray()
        repeat(70) { index ->
            entries.put(
                if (index < 2) duplicate
                else track("/api/timedtext?v=video123&lang=lang$index", language = "lang$index", name = "Track $index"),
            )
        }
        val parsed = YouTubeCaptionTrackParser.parse(
            JSONObject().put(
                "captions",
                JSONObject().put(
                    "playerCaptionsTracklistRenderer",
                    JSONObject().put("captionTracks", entries)
                        .put("translationLanguages", JSONArray().put(JSONObject().put("languageCode", "fr"))),
                ),
            ),
            "video123",
        )

        assertEquals(63, parsed.size)
        assertEquals(1, parsed.count { it.label == "English" })
        assertFalse(parsed.any { it.languageCode == "fr" })
        assertTrue(YouTubeCaptionTrackParser.parse(JSONObject(), "video123").isEmpty())
    }

    private fun playerWithTracks(vararg tracks: JSONObject): JSONObject = JSONObject().put(
        "captions",
        JSONObject().put(
            "playerCaptionsTracklistRenderer",
            JSONObject().put("captionTracks", JSONArray(tracks.toList())),
        ),
    )

    private fun track(
        url: String,
        language: String = "en",
        name: String,
        kind: String? = null,
        vssId: String = ".en",
    ): JSONObject = JSONObject()
        .put("baseUrl", url)
        .put("languageCode", language)
        .put("name", JSONObject().put("runs", JSONArray().put(JSONObject().put("text", name))))
        .put("vssId", vssId)
        .apply { kind?.let { put("kind", it) } }
}
